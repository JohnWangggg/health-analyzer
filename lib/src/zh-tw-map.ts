const TITLE_PHRASES: Array<[string, string]> = TITLE_PHRASES_RAW.slice().sort(
  (a, b) => b[0].length - a[0].length
);

/**
 * Convert Simplified Chinese analysis strings to Traditional for zh-TW.
 * Phrase dictionary (longest-first). Idempotent on already-Traditional text.
 * Alias: toTraditionalText.
 */
export function toTraditionalTitle(s: string): string {
  if (!s) return s;
  let out = s;
  for (const [from, to] of TITLE_PHRASES) {
    if (out.includes(from)) {
      out = out.split(from).join(to);
    }
  }
  return out;
}

/** @see toTraditionalTitle */
export const toTraditionalText = toTraditionalTitle;

/**
 * Apply toTraditionalTitle to markdown ## / ### heading lines only.
 */
export function traditionalizeMarkdownHeadings(md: string): string {
  if (!md) return md;
  return md
    .split('\n')
    .map((line) => {
      const m = /^(#{1,6}\s+)(.*)$/.exec(line);
      if (!m) return line;
      return m[1] + toTraditionalTitle(m[2]);
    })
    .join('\n');
}

/**
 * Traditionalize free-form analysis body (insights detail, signals, status).
 * Same dictionary as titles; safe to call repeatedly.
 */
export function traditionalizeAnalysisCopy(s: string): string {
  return toTraditionalTitle(s);
}
